"""
Relabel-and-regenerate negatives for DPO (round 3d).

Idea (user, 2026-10-06): the gold reasoning in train.jsonl was produced by the
label-conditioned v1 distillation prompt (Knowledge_Distillation/
knowledge_distillation.py: the teacher sees Is_Safe + Risk_Categories and
justifies them), then cleaned by SFT/clean_reasoning.py. So a negative that is
"the same reasoning, written the same way, but with one risk factor missed" can
be produced by running THE SAME prompt on THE SAME profile with the ground-truth
labels altered:

  FN  for an unsafe row with k >= 2 true categories, each true category c in
      turn is set to False (is_safe stays False); the teacher writes the full
      audit justifying that reduced label set  ->  rejected
  FP  (optional, --fp) for an unsafe row, one evidence-adjacent false category
      is set to True (is_safe stays False)        ->  rejected

The chosen is the gold answer. With --sym the chosen is ALSO regenerated by the
same teacher under the TRUE labels, so both sides come from one process (same
teacher, same prompt, same cleaning) and the only systematic difference is the
missed / added factor. Both pair files are written when --sym is on.

Outputs (in <out dir>):
  relabel_teacher.jsonl         cache {pid, kind, cat, reasoning_raw, reasoning}
  dpo_pairs_relabel_gold.jsonl  chosen = gold
  dpo_pairs_relabel_sym.jsonl   chosen = regenerated under true labels (--sym)

    source ~/.hive_key && KD_PROVIDER=hive python Claude/DPO/build_teacher_relabel_pairs.py \
        --cap-rows 3 --out-dir Claude/DPO/data/teacher_relabel_pilot
    source ~/.hive_key && KD_PROVIDER=hive python Claude/DPO/build_teacher_relabel_pairs.py \
        --sym --workers 12 --out-dir Claude/DPO/data/teacher_relabel
"""
import argparse
import csv
import json
import os
import random
import re
import sys
import time
from collections import Counter
from concurrent.futures import ThreadPoolExecutor, as_completed
from pathlib import Path

HERE = Path(__file__).resolve().parent
REPO = HERE.parent.parent
sys.path.insert(0, str(HERE))
sys.path.insert(0, str(REPO / "Claude/SFT"))
from build_teacher_audit_pairs import (  # noqa: E402
    PROVIDERS, TRAIN, audit_line_re, decision_is_true, has_evidence, load_cats, schema_suffix,
)
from clean_reasoning import fix_unicode, strip_leakage, unify_headers  # noqa: E402

CSV = REPO / "Claude/Knowledge_Distillation/Claude_Personalized_Groundtruth_New_Data_Distill.csv"
# columns that did not exist when the gold was distilled (outputs of that run) + the short rationale
HIDDEN = {"Reasoning", "Teacher_Reasoning", "Trace_Valid", "Validation_Note"}

# ---- v1 prompt, copied verbatim from Knowledge_Distillation/knowledge_distillation.py
V1_SYSTEM = ("You are a lead clinical pharmacologist specializing in critique-augmented safety audits. "
             "You justify ground-truth verdicts with deliberative, profile-aware reasoning.")


def build_protocol(is_safe):
    if not is_safe:
        return """
[Audit Protocol: UNSAFE CASE]
1. CONFLICT IDENTIFICATION: Pinpoint the specific patient attribute(s)
   (Genetic Disorder, Chronic Condition, Current Medication, Allergy,
   Impairment, Lifestyle factor, etc.) that create the hazard.
2. PHARMACOLOGICAL RULE: Cite the underlying medical constraint or
   drug-drug / drug-food interaction mechanism.
3. LOGICAL BRIDGE: Explain how the patient's specific profile overrides
   general safety assumptions to necessitate the 'Unsafe' verdict.
"""
    return """
[Verification Protocol: SAFE CASE]
1. CONSTRAINT CHECK: Confirm that personalized factors (Renal, Hepatic,
   Cardiac, Respiratory, Allergies, Pregnancy, Lifestyle) were reviewed
   and no clinically significant conflicts exist.
2. DOSE/BMI ALIGNMENT: Verify the dosage is appropriate given the
   patient's Weight/BMI and Age.
3. NEAR-MISS NOTING: If any profile element looked concerning at first
   glance but was ruled out on closer inspection, briefly explain why.
"""


def build_prompt(row, cats):
    context_data = {k: v for k, v in row.items() if k not in HIDDEN}
    is_safe = str(row.get("Is_Safe", "")).strip().upper() == "TRUE"
    protocol = build_protocol(is_safe)
    category_list = "\n".join(f"   - {c}" for c in cats)
    return f"""[Task]
You are a Lead Clinical Pharmacologist performing a deliberative safety
audit. Produce a structured natural-language critique justifying the
GROUND-TRUTH safety verdict.

[Patient Profile, Clinical Scenario, and Ground Truth]
{json.dumps(context_data, indent=2)}

[Strict Instructions]
1. The 'Is_Safe' label and 'Risk_Categories' booleans are verified
   CLINICAL GROUND TRUTH from drugbank.com and drugs.com.
   Do NOT second-guess, criticize, or argue against them.

{protocol}

2. CATEGORY AUDIT (REQUIRED): Address each of the {len(cats)} risk categories
   below in order. For categories flagged TRUE, explain the specific
   patient-profile trigger. For categories flagged FALSE, state in one
   short line why they do not apply (e.g., "Renal: CrCl 95 mL/min —
   normal, no concern").
{category_list}

3. FINAL VERDICT: One sentence linking the deciding factor(s) to the
   ground-truth Is_Safe label.

[Style Requirements]
- Use slow, deliberative reasoning.
- Total length: 250–450 tokens. Be concise on FALSE categories.
- Respond ONLY with the reasoning text. No preamble, no JSON, no
  markdown headers other than the section labels above.
"""


def clean(text):
    """Same post-processing the gold went through (clean_reasoning.py)."""
    text = fix_unicode(text)
    text, _ = unify_headers(text)
    text, _, _ = strip_leakage(text)
    text = re.sub(r"^```[a-zA-Z]*\s*|\s*```$", "", text.strip(), flags=re.S).strip()
    return text


def validate(text, labels, cats, must_cat=None):
    """Reasoning must carry the altered labels in its audit and the right verdict."""
    n_words = len(text.split())
    if not (80 <= n_words <= 800):
        return f"len_{n_words}"
    if "CATEGORY AUDIT" not in text or "FINAL VERDICT" not in text:
        return "missing_section"
    parsed = 0
    for c in cats:
        m = audit_line_re(c).search(text)
        if not m:
            if c == must_cat:
                return "target_line_unparsed"
            continue
        parsed += 1
        if decision_is_true(m.group("decision")) != bool(labels[c]):
            return f"audit_mismatch:{c}"
    if parsed < 12:
        return f"audit_parsed_{parsed}"
    is_safe = not any(labels.values())
    v = text[text.rfind("FINAL VERDICT"):].lower()
    says_unsafe = re.search(r"\bunsafe\b|not safe\b", v) is not None
    if is_safe == says_unsafe:
        return "verdict_mismatch"
    if re.search(r"ground[\s\-]?truth|\[(?:audit|verification) protocol", text, re.I):
        return "leakage_left"
    return None


def pid_of(user_text):
    m = re.search(r"^- Patient ID:\s*(\d+)", user_text, re.M)
    return m.group(1) if m else None


def main():
    ap = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    ap.add_argument("--train", default=str(TRAIN))
    ap.add_argument("--csv", default=str(CSV))
    ap.add_argument("--out-dir", required=True)
    ap.add_argument("--cap-rows", type=int, default=None, help="max source rows (pilot)")
    ap.add_argument("--fp", action="store_true", help="also build FP negatives (one false category set True)")
    ap.add_argument("--fp-cap", type=int, default=200, help="max FP negatives per category")
    ap.add_argument("--sym", action="store_true", help="also regenerate the chosen under the true labels")
    ap.add_argument("--workers", type=int, default=12)
    ap.add_argument("--seed", type=int, default=0)
    ap.add_argument("--no-schema", action="store_true")
    ap.add_argument("--dry-run", action="store_true")
    args = ap.parse_args()
    rng = random.Random(args.seed)

    out_dir = Path(args.out_dir)
    out_dir.mkdir(parents=True, exist_ok=True)
    cache_path = out_dir / "relabel_teacher.jsonl"

    cats = load_cats()
    suffix = "" if args.no_schema else schema_suffix(cats)
    rows = [json.loads(l) for l in open(args.train) if l.strip()]
    csv.field_size_limit(10 ** 9)
    by_pid = {r["Patient ID"]: r for r in csv.DictReader(open(args.csv, encoding="utf-8"))}

    # ---- plan
    jobs = []            # (pid, kind, cat, labels)
    src = {}             # pid -> train idx
    fp_count = Counter()
    n_rows = 0
    order = list(range(len(rows)))
    rng.shuffle(order)
    for i in order:
        user = rows[i]["messages"][1]["content"]
        gold = json.loads(rows[i]["messages"][-1]["content"])
        pid = pid_of(user)
        if pid is None or pid not in by_pid or gold["is_safe"]:
            continue
        labels = {c: bool(gold["risk_analysis"].get(c, False)) for c in cats}
        trues = [c for c in cats if labels[c]]
        row_jobs = []
        if len(trues) >= 2:
            for c in trues:
                alt = dict(labels); alt[c] = False
                row_jobs.append((pid, "FN", c, alt))
        if args.fp and trues:
            cands = [c for c in cats if not labels[c] and has_evidence(user, c) and fp_count[c] < args.fp_cap]
            if cands:
                c = rng.choice(cands)
                alt = dict(labels); alt[c] = True
                row_jobs.append((pid, "FP", c, alt)); fp_count[c] += 1
        if not row_jobs:
            continue
        if args.cap_rows and n_rows >= args.cap_rows:
            break
        n_rows += 1
        src[pid] = i
        jobs.extend(row_jobs)
        if args.sym:
            jobs.append((pid, "chosen", "", labels))
    kinds = Counter(j[1] for j in jobs)
    print(f"plan: {n_rows} source rows, {len(jobs)} teacher calls {dict(kinds)}")
    if args.dry_run:
        pid, kind, c, labels = jobs[0]
        row = dict(by_pid[pid]); row["Risk_Categories"] = json.dumps(labels); row["Is_Safe"] = "False"
        print(f"\n--- example {kind} {c} ---\n" + build_prompt(row, cats)[:3000])
        return 0

    cache = {}
    if cache_path.exists():
        for l in open(cache_path):
            d = json.loads(l)
            cache[(d["pid"], d["kind"], d["cat"])] = d["reasoning"]
    todo = [j for j in jobs if (j[0], j[1], j[2]) not in cache]
    print(f"cache: {len(cache)}  to call: {len(todo)}")

    prov = os.environ.get("KD_PROVIDER", "hive").lower()
    P = PROVIDERS[prov]
    key = os.environ.get(P["key_env"])
    if not key:
        sys.exit(f"Set {P['key_env']} (KD_PROVIDER={prov}).")
    model = os.environ.get("KD_MODEL") or P["model"]
    reasoning_effort = os.environ.get("KD_REASONING_EFFORT", P.get("reasoning_effort"))
    from openai import OpenAI  # noqa: E402
    client = OpenAI(api_key=key, base_url=os.environ.get("KD_BASE_URL", P["base_url"]), timeout=300, max_retries=0)
    print(f"teacher: {prov} / {model}  reasoning_effort={reasoning_effort}")

    def work(job):
        pid, kind, c, labels = job
        row = dict(by_pid[pid])
        row["Risk_Categories"] = json.dumps(labels)
        row["Is_Safe"] = "True" if not any(labels.values()) else "False"
        prompt = build_prompt(row, cats)
        last = "no_attempt"
        for attempt in range(3):
            try:
                kw = dict(model=model, temperature=0.7, max_completion_tokens=8000,
                          messages=[{"role": "system", "content": V1_SYSTEM},
                                    {"role": "user", "content": prompt}])
                if reasoning_effort:
                    kw["extra_body"] = {"reasoning_effort": reasoning_effort}
                raw = client.chat.completions.create(**kw).choices[0].message.content or ""
                text = clean(raw)
                why = validate(text, labels, cats, must_cat=c or None)
                if why is None:
                    return pid, kind, c, raw, text, "ok"
                last = why
            except Exception as e:  # noqa: BLE001
                msg = str(e)
                last = "api:" + msg[:50]
                time.sleep((8 if ("429" in msg or "Too Many" in msg) else 3) * (attempt + 1))
        return pid, kind, c, None, None, last

    t0 = time.time()
    n_ok, fails = 0, Counter()
    if todo:
        with open(cache_path, "a") as cf, ThreadPoolExecutor(max_workers=args.workers) as pool:
            futs = [pool.submit(work, j) for j in todo]
            for k, f in enumerate(as_completed(futs), 1):
                pid, kind, c, raw, text, why = f.result()
                if text:
                    cache[(pid, kind, c)] = text
                    cf.write(json.dumps({"pid": pid, "kind": kind, "cat": c, "reasoning_raw": raw,
                                         "reasoning": text}, ensure_ascii=False) + "\n")
                    cf.flush()
                    n_ok += 1
                else:
                    fails[why.split(":")[0] if why.startswith("api") else why.split(":")[0]] += 1
                if k % 50 == 0:
                    print(f"  {k}/{len(todo)}  ok {n_ok} fail {sum(fails.values())}  {(time.time()-t0)/60:.1f} min",
                          flush=True)
        print(f"teacher done: ok {n_ok} fail {sum(fails.values())}  reasons {dict(fails.most_common(8))}")

    # ---- assemble
    def dumps(reasoning, labels):
        return json.dumps({"reasoning": reasoning, "risk_analysis": labels, "is_safe": not any(labels.values())},
                          indent=2, ensure_ascii=False)

    n_gold, n_sym = Counter(), Counter()
    f_gold = (out_dir / "dpo_pairs_relabel_gold.jsonl").open("w", encoding="utf-8")
    f_sym = (out_dir / "dpo_pairs_relabel_sym.jsonl").open("w", encoding="utf-8") if args.sym else None
    for pid, kind, c, labels in jobs:
        if kind == "chosen":
            continue
        rej = cache.get((pid, kind, c))
        if not rej:
            continue
        i = src[pid]
        msgs = rows[i]["messages"]
        gold = json.loads(msgs[-1]["content"])
        gold_labels = {k: bool(gold["risk_analysis"].get(k, False)) for k in cats}
        prompt = [dict(m) for m in msgs if m["role"] != "assistant"]
        if suffix:
            for m in prompt:
                if m["role"] == "system":
                    m["content"] += suffix
                    break
        rec = {"neg_type": f"teacher_relabel_{kind}", "changed_category": c, "source_idx": i, "pid": pid,
               "prompt": prompt, "rejected": [{"role": "assistant", "content": dumps(rej, labels)}]}
        f_gold.write(json.dumps({**rec, "chosen": [{"role": "assistant", "content": msgs[-1]["content"]}]},
                                ensure_ascii=False) + "\n")
        n_gold[(kind, c)] += 1
        if f_sym is not None:
            ch = cache.get((pid, "chosen", ""))
            if ch:
                f_sym.write(json.dumps({**rec, "chosen": [{"role": "assistant", "content": dumps(ch, gold_labels)}]},
                                       ensure_ascii=False) + "\n")
                n_sym[(kind, c)] += 1
    f_gold.close()
    if f_sym is not None:
        f_sym.close()
    print(f"wrote {sum(n_gold.values())} pairs -> {out_dir/'dpo_pairs_relabel_gold.jsonl'}"
          + (f"  and {sum(n_sym.values())} -> dpo_pairs_relabel_sym.jsonl" if f_sym is not None else ""))
    for (d, c), n in sorted(n_gold.items(), key=lambda kv: (kv[0][1], kv[0][0])):
        print(f"  {d} {c:<40s} {n:4d}")
    return 0


if __name__ == "__main__":
    sys.exit(main())
